    private fun icon(name: String, pathData: String): ImageVector =
        ImageVector.Builder(
            name = name,
            defaultWidth = 24.dp,
            defaultHeight = 24.dp,
            viewportWidth = 24f,
            viewportHeight = 24f,
        ).addPath(
            pathData = addPathNodes(pathData),
            fill = SolidColor(Color.White),
        ).build()

    private fun icon(name: String, vararg pathData: String): ImageVector {
        var b = ImageVector.Builder(
            name = name,
            defaultWidth = 24.dp,
            defaultHeight = 24.dp,
            viewportWidth = 24f,
            viewportHeight = 24f,
        )
        for (p in pathData) {
            b = b.addPath(pathData = addPathNodes(p), fill = SolidColor(Color.White))
        }
        return b.build()
    }

